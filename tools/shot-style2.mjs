import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PORT = 8146;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const server = spawn(process.execPath, [path.join(ROOT, 'tools', 'serve.mjs'), String(PORT)], { stdio: 'ignore' });
await sleep(500);
const browser = await puppeteer.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true, args: ['--no-sandbox', '--mute-audio'] });
const page = await browser.newPage();
await page.setViewport({ width: 1100, height: 1300, deviceScaleFactor: 1.4 });
page.on('pageerror', (e) => console.log('[err]', e.message));
page.on('response', (r) => { if (r.status() >= 400) console.log('[404]', r.url()); });
await page.goto(`http://127.0.0.1:${PORT}/${encodeURIComponent('畫風樣本2.html')}`, { waitUntil: 'networkidle2' });
await sleep(700);
await page.screenshot({ path: path.join(ROOT, 'screenshots', 'style-options-2.png'), fullPage: true });
console.log('ok');
await browser.close();
server.kill();
